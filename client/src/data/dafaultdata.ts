// ============================================================
// GENERATE RANDOM USERS
// ============================================================

export interface DefaultUser {
  id: string
  firstName: string
  lastName: string
  time: string
  location: string
  image: string
  avatar: string
  bio: string
  gender: string
  interested_in: string
  min_age: number
  max_age: number
}

export function generateRandomUsers(count: number = 20): DefaultUser[] {
  const users: DefaultUser[] = []
  for (let i = 0; i < count; i++) {
    const firstName = firstNames[Math.floor(Math.random() * firstNames.length)]
    const lastName = lastNames[Math.floor(Math.random() * lastNames.length)]
    const gender = genders[Math.floor(Math.random() * genders.length)]
    
    users.push({
      id: `user-${i + 1}`,
      firstName,
      lastName,
      time: timeOptions[Math.floor(Math.random() * timeOptions.length)],
      location: locations[Math.floor(Math.random() * locations.length)],
      image: imageUrls[i % imageUrls.length],
      avatar: avatarUrls[i % avatarUrls.length],
      bio: bios[Math.floor(Math.random() * bios.length)],
      gender: gender,
      interested_in: 'Men',
      min_age: Math.floor(Math.random() * 5) + 20,
      max_age: Math.floor(Math.random() * 10) + 28,
    })
  }
  return users
}

// Export default users for easy import
export const defaultUsers = generateRandomUsers(20)